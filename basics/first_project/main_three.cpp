#include <iostream>

using namespace std;

int main()
{

    int myInt;
    myInt = 15;
    double myDouble = 3.14;

    cout << "The value of myInt is: " << myInt << endl;
    cout << "The value of myDouble is: " << myDouble << endl;
    cout << "The sum of myInt and myDouble is: " << myInt + myDouble << endl;
    return 0;
}